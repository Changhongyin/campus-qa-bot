const KB_START = '【知识库资料片段开始】';
const KB_END = '【知识库资料片段结束】';

const KB_FALLBACK =
  '（本轮未检索到相关片段：可基于对学校的通用认知谨慎回答，但不要编造具体的数字、日期、地点或人名，并提醒同学以学校官方渠道的信息为准）';

/** Chunk text is untrusted data: it must not be able to forge the data block markers or chunk labels. */
function neutralize(text: string): string {
  return text.replace(/【(?=知识库资料片段|资料片段)/g, '［');
}

export function buildSystemPrompt(chunks: Chunk[]): string {
  const kb = chunks.length
    ? chunks
        .map((c, i) => '【资料片段' + (i + 1) + '｜来源：' + c.source + '】\n' + neutralize(c.text))
        .join('\n\n')
    : KB_FALLBACK;

  return [INVARIANT_PROMPT, KB_START, kb, KB_END].join('\n');
}

